#!/usr/bin/env python3
"""Build the SQL Editor artifact without changing the reviewed migration."""

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VERSION = "20261111120000"
NAME = "accept_match_draft"
SOURCE = ROOT / "supabase/migrations" / f"{VERSION}_{NAME}.sql"
OUTPUT = ROOT / "supabase/tools/accept_match_draft_operator.sql"
BEGIN_SOURCE = b"-- BEGIN CANONICAL MIGRATION\n"
END_SOURCE = b"-- END CANONICAL MIGRATION\n"

READINESS = """select
  to_regprocedure('public.accept_match_draft(uuid,uuid,uuid,jsonb)') is not null
    as function_exists,
  coalesce(has_function_privilege('authenticated',
    to_regprocedure('public.accept_match_draft(uuid,uuid,uuid,jsonb)'), 'EXECUTE'), false)
    as authenticated_execute_allowed,
  not coalesce(has_function_privilege('anon',
    to_regprocedure('public.accept_match_draft(uuid,uuid,uuid,jsonb)'), 'EXECUTE'), true)
    as anonymous_execute_denied,
  coalesce((select not prosecdef from pg_proc
    where oid = to_regprocedure('public.accept_match_draft(uuid,uuid,uuid,jsonb)')), false)
    as invoker_mode"""


def generate(source: bytes) -> bytes:
    """Keep source bytes intact; history stores the same SQL as one statement."""
    text = source.decode("utf-8")
    tag = "$canonical_history$"
    if tag in text:
        raise ValueError("Canonical source collides with the history quote delimiter")
    digest = hashlib.sha256(source).hexdigest()
    prefix = f"""-- Generated by supabase/tools/generate_draft_rollout.py. Do not edit.
-- Canonical source: supabase/migrations/{VERSION}_{NAME}.sql
-- Canonical SHA256: {digest}
-- Run the WHOLE file once in SQL Editor. A failure requires ROLLBACK, not retry edits.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';
DO $preflight$
BEGIN
  -- Serialize this operator step; ordinary DDL and history constraints still apply.
  PERFORM pg_advisory_xact_lock(20261111, 120000);
  IF EXISTS (SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
             WHERE n.nspname = 'public' AND p.proname = '{NAME}')
     OR to_regclass('public.match_draft_acceptances') IS NOT NULL THEN
    RAISE EXCEPTION 'Draft acceptance objects already exist; stop for schema review';
  END IF;
  IF to_regclass('supabase_migrations.schema_migrations') IS NOT NULL THEN
    IF NOT EXISTS (SELECT 1 FROM pg_class
                   WHERE oid = to_regclass('supabase_migrations.schema_migrations')
                     AND relkind = 'r') THEN
      RAISE EXCEPTION 'Unsupported migration history relation; stop for history review';
    END IF;
    LOCK TABLE supabase_migrations.schema_migrations IN EXCLUSIVE MODE;
    IF EXISTS (SELECT 1 FROM supabase_migrations.schema_migrations
               WHERE version = '{VERSION}') THEN
      RAISE EXCEPTION 'Migration version already recorded; stop for history review';
    END IF;
  END IF;
END;
$preflight$;
""".encode("utf-8")
    suffix = f"""DO $history$
DECLARE
  columns_sql text := 'version';
  values_sql text := '$1';
  inserted_rows bigint;
BEGIN
  -- Never create a history table or invent entries for older migrations.
  IF to_regclass('supabase_migrations.schema_migrations') IS NOT NULL THEN
    IF EXISTS (SELECT 1 FROM pg_attribute
               WHERE attrelid = 'supabase_migrations.schema_migrations'::regclass
                 AND attname = 'name' AND NOT attisdropped) THEN
      columns_sql := columns_sql || ', name';
      values_sql := values_sql || ', $2';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_attribute
               WHERE attrelid = 'supabase_migrations.schema_migrations'::regclass
                 AND attname = 'statements' AND NOT attisdropped) THEN
      columns_sql := columns_sql || ', statements';
      values_sql := values_sql || ', $3';
    END IF;
    -- Unknown required columns or incompatible types fail the whole transaction.
    -- No ON CONFLICT, UPDATE, baseline repair, or history overwrite.
    EXECUTE 'INSERT INTO supabase_migrations.schema_migrations (' || columns_sql ||
            ') VALUES (' || values_sql || ')'
      USING '{VERSION}'::text, '{NAME}'::text,
            ARRAY[{tag}{text}{tag}]::text[];
    GET DIAGNOSTICS inserted_rows = ROW_COUNT;
    IF inserted_rows <> 1 OR (SELECT count(*) FROM supabase_migrations.schema_migrations
                             WHERE version = '{VERSION}') <> 1 THEN
      RAISE EXCEPTION 'Migration history insert not retained; transaction must roll back';
    END IF;
  END IF;
END;
$history$;
DO $verify$
BEGIN
  IF NOT (SELECT function_exists AND authenticated_execute_allowed
                 AND anonymous_execute_denied AND invoker_mode
          FROM ({READINESS}) readiness) THEN
    RAISE EXCEPTION 'Draft acceptance metadata checks failed; transaction must roll back';
  END IF;
END;
$verify$;
-- PostgreSQL delivers this notification only if COMMIT succeeds.
NOTIFY pgrst, 'reload schema';
COMMIT;

-- Metadata only. This does not prove hosted PostgREST cache or JWT/RLS behavior.
{READINESS},
  to_regclass('supabase_migrations.schema_migrations') is not null
    as migration_history_present;
""".encode("utf-8")
    # A separator is outside the exact canonical byte span (also for a missing LF).
    return prefix + BEGIN_SOURCE + source + b"\n" + END_SOURCE + suffix


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if artifact is stale")
    args = parser.parse_args()
    artifact = generate(SOURCE.read_bytes())
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_bytes() != artifact:
            parser.exit(1, f"Stale artifact: {OUTPUT}\n")
        print("Artifact matches canonical source and generator.")
    else:
        OUTPUT.write_bytes(artifact)
        print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
